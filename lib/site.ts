/**
 * Per-page metadata in one place. Next inherits an unset openGraph/twitter
 * block wholesale from the nearest parent that sets one, so every route goes
 * through here rather than sharing the homepage's social card by accident.
 */
export function pageMetadata({
  title,
  description,
  path,
}: {
  title: string;
  description: string;
  path: string;
}) {
  const url = `${SITE_URL}${path}`;
  return {
    title,
    description,
    alternates: { canonical: url },
    openGraph: {
      type: "website" as const,
      locale: "el_GR",
      url,
      title,
      description,
      siteName: therapist.brand,
    },
    twitter: { card: "summary_large_image" as const, title, description },
  };
}

